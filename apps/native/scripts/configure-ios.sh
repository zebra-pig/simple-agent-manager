#!/bin/sh
# Writes ios/Config/Local.xcconfig (gitignored) from SAM_* and BASE_DOMAIN environment variables,
# overriding the upstream defaults in ios/Config/Brand.xcconfig. Unset variables
# keep their default, so running this with nothing set builds the upstream app.
#
#   SAM_TEAM_ID         Apple Developer team id (10 characters)
#   SAM_BUNDLE_ID       bundle id, e.g. com.example.sam
#   SAM_APP_NAME        name under the icon
#   BASE_DOMAIN         the deployment to suggest, same as the platform's BASE_DOMAIN
#                       (e.g. sam.example.com: the app uses api.sam.example.com)
#   SAM_MARKETING_VERSION, SAM_BUILD_NUMBER  (CI_BUILD_NUMBER on Xcode Cloud)
set -eu

out="$(cd "$(dirname "$0")/.." && pwd)/ios/Config/Local.xcconfig"
: "${SAM_BUILD_NUMBER:=${CI_BUILD_NUMBER:-}}"

{
  echo "// Generated by scripts/configure-ios.sh. Do not commit."
  for name in SAM_TEAM_ID SAM_BUNDLE_ID SAM_APP_NAME BASE_DOMAIN SAM_MARKETING_VERSION SAM_BUILD_NUMBER; do
    value="$(printenv "$name" || true)"
    [ -n "$value" ] || continue
    case "$value" in
      *//* | *"
"*) echo "error: $name must be one line without '//' (xcconfig comment)" >&2; exit 1 ;;
    esac
    echo "$name = $value"
  done
} > "$out"

echo "Wrote $out:"
sed 1d "$out" | sed 's/^/  /'
